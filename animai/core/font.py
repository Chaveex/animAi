"""Built-in 3x5 bitmap font, so control images never depend on a system font."""
from __future__ import annotations

import numpy as np

_GLYPHS = {
    "0": "111/101/101/101/111", "1": "010/110/010/010/111", "2": "111/001/111/100/111",
    "3": "111/001/111/001/111", "4": "101/101/111/001/001", "5": "111/100/111/001/111",
    "6": "111/100/111/101/111", "7": "111/001/001/001/001", "8": "111/101/111/101/111",
    "9": "111/101/111/001/111",
    "A": "111/101/111/101/101", "B": "110/101/110/101/110", "C": "111/100/100/100/111",
    "D": "110/101/101/101/110", "E": "111/100/111/100/111", "F": "111/100/111/100/100",
    "G": "111/100/101/101/111", "H": "101/101/111/101/101", "I": "111/010/010/010/111",
    "J": "001/001/001/101/111", "K": "101/101/110/101/101", "L": "100/100/100/100/111",
    "M": "101/111/111/101/101", "N": "110/101/101/101/101", "O": "111/101/101/101/111",
    "P": "111/101/111/100/100", "Q": "111/101/101/111/001", "R": "111/101/110/101/101",
    "S": "011/100/010/001/110", "T": "111/010/010/010/010", "U": "101/101/101/101/111",
    "V": "101/101/101/101/010", "W": "101/101/111/111/101", "X": "101/101/010/101/101",
    "Y": "101/101/010/010/010", "Z": "111/001/010/100/111",
    "_": "000/000/000/000/111", "-": "000/000/111/000/000", ".": "000/000/000/000/010",
    ",": "000/000/000/010/100", ":": "000/010/000/010/000", "/": "001/001/010/100/100",
    "#": "101/111/101/111/101", "(": "010/100/100/100/010", ")": "010/001/001/001/010",
    "=": "000/111/000/111/000", "+": "000/010/111/010/000", "%": "101/001/010/100/101",
    " ": "000/000/000/000/000", "?": "111/001/010/000/010",
}
GLYPH_W, GLYPH_H = 3, 5


def text_size(text: str, scale: int = 1) -> tuple[int, int]:
    n = len(text)
    return (max(0, n * (GLYPH_W + 1) - 1) * scale, GLYPH_H * scale)


def draw_text(img: np.ndarray, x: int, y: int, text: str, color=(255, 255, 255),
              scale: int = 1, bg=None) -> None:
    """Draw ``text`` (upper-cased) on an RGB array in place; clipped at the borders."""
    h, w = img.shape[:2]
    tw, th = text_size(text, scale)
    if bg is not None:
        img[max(0, y - scale):max(0, y + th + scale), max(0, x - scale):max(0, x + tw + scale)] = bg
    cx = x
    for ch in text.upper():
        rows = _GLYPHS.get(ch, _GLYPHS["?"]).split("/")
        for ry, row in enumerate(rows):
            for rx, bit in enumerate(row):
                if bit == "1":
                    x0, y0 = cx + rx * scale, y + ry * scale
                    if x0 >= w or y0 >= h or x0 + scale <= 0 or y0 + scale <= 0:
                        continue
                    img[max(0, y0):y0 + scale, max(0, x0):x0 + scale] = color
        cx += (GLYPH_W + 1) * scale
